namespace PracticalWork3.Gui;

/// <summary>Текст справки: что такое список, что означают L, x, E, F, i, j и что делает каждая операция.</summary>
internal static class HelpText
{
    public const string Full =
@"ЧТО ТАКОЕ СПИСОК
Односвязный список — цепочка узлов. В каждом узле лежит число и ссылка на следующий узел. Первый узел называется HEAD (голова), последний — TAIL (хвост); ссылка хвоста пустая (∅). На рисунке узел выглядит так: [ число | • ], стрелка ведёт к следующему узлу.

ОБОЗНАЧЕНИЯ (как в задании)
L — основной список, с которым работает операция. Его вы вводите в поле «Список L»: целые числа через пробел, например  5 3 8 3 1 5 9 3 7.
x — число, которое ищется в L. Всегда берётся его ПЕРВОЕ вхождение (пп. 5 и 10).
E — в пп. 6, 7, 8 это ЧИСЛО (элемент). В п. 6 его вставляют в список, в п. 7 удаляют все такие числа, в п. 8 перед его первым вхождением вставляют F.
E — в п. 9 это второй СПИСОК, который дописывается в конец L (для него появляется отдельное поле).
F — новое число, которое вставляется в п. 8.
i, j — номера позиций для п. 12. Счёт идёт с нуля: первый элемент имеет номер 0, второй — 1 и так далее.

КАК ЧИТАТЬ КАРТИНКУ
ДО — список до операции, ПОСЛЕ — результат. Цвета:
  жёлтый — найденный или затронутый элемент;
  зелёный — новый или перемещённый элемент;
  красный (зачёркнут) — элемент, который будет удалён.
Если в конце строки состояния написано, что нарушена согласованность Head/Tail/Count, значит, в алгоритме ошибка (в норме этого не бывает).

ОПЕРАЦИИ
1. Перевернуть список. Пример: [1,2,3] → [3,2,1].
2а. Последний элемент в начало. [1,2,3] → [3,1,2].
2б. Первый элемент в конец. [1,2,3] → [2,3,1].
3. Сколько в L различных элементов. [5,3,5,1,3] → 3 (это 5, 3 и 1).
4. Удалить неуникальные: убираются ВСЕ значения, которые встречаются больше одного раза. [5,3,8,3,1,5,9,3,7] → [8,1,9,7].
4*. Другое прочтение п. 4: оставить по одному (первому) вхождению. [5,3,8,3,1,5,9,3,7] → [5,3,8,1,9,7].
5. Вставить список в себя после первого x: сразу после первого x вставляется копия всего L. L=[1,2,3,4], x=2 → [1,2,1,2,3,4,3,4]. Если x нет, список не меняется.
6. Вставить E в упорядоченный список. L должен быть непустым и идти по неубыванию. L=[1,3,5], E=4 → [1,3,4,5]. Кнопка «Отсортировать» поможет подготовить список.
7. Удалить все элементы E. L=[3,1,3,2], E=3 → [1,2].
8. Вставить F перед первым E. L=[1,2,3,2], E=2, F=9 → [1,9,2,3,2]. Если E нет, список не меняется.
9. Дописать список E в конец L. L=[1,2], E=[3,4,5] → [1,2,3,4,5]. Узлы E переезжают в L, сам E после этого пуст.
10. Разбить L по первому вхождению x на две части. Само x в обе части не попадает. L=[1,2,3,4,5], x=3 → первая [1,2], вторая [4,5]. Исходный L после этого пуст (его узлы разошлись по частям). Если x нет — первая часть весь список, вторая пуста.
11. Удвоить список: к L приписывается его копия. [1,2,3] → [1,2,3,1,2,3].
12. Поменять местами элементы с номерами i и j (счёт с нуля). L=[1,2,3,4,5], i=0, j=4 → [5,2,3,4,1].

ПОЛЕЗНО
Флажок «результат → новый список L» подставляет результат в поле L, чтобы можно было применять операции одну за другой.
Кнопка «Случайный список» создаёт список из 5–10 чисел от 1 до 9.
В списке может быть не больше 40 элементов.";
}
